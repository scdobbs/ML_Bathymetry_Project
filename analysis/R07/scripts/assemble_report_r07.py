"""Splice the generated tables into the R07 report. Markers in REPORT_R07_template.md:
  {{table:NAME}}           -> R07/tables/NAME.md (generated by report_tables_r07.py), verbatim
  {{scores:HEADING}}       -> the section of scores/R07_scores.md (score_r07.py) whose '## ' heading starts with HEADING, verbatim
Writes REPORT_R07_2026-10-07.md. No number in the report tables is typed by hand."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import r07_common as R7
REP = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); TAB = f"{REP}/tables"
scores = open(f"{R7.SCORES}/R07_scores.md").read()
def section(prefix):
    parts = re.split(r"\n(?=## )", scores)
    hits = [p for p in parts if p.startswith("## " + prefix)]
    assert hits, f"no scores section starting with {prefix!r}"
    body = hits[0].split("\n", 1)[1].strip("\n")
    return f"<!-- from scores/R07_scores.md (score_r07.py), section '{hits[0].splitlines()[0][3:]}' -->\n{body}"
def table(name): return open(f"{TAB}/{name}.md").read().rstrip("\n")
src = open(f"{REP}/REPORT_R07_template.md").read()
out = re.sub(r"\{\{table:([^}]+)\}\}", lambda m: table(m.group(1)), src)
out = re.sub(r"\{\{scores:([^}]+)\}\}", lambda m: section(m.group(1)), out)
assert "{{" not in out, re.findall(r"\{\{[^}]+\}\}", out)
open(f"{REP}/REPORT_R07_2026-10-07.md", "w").write(out); print(f"wrote REPORT_R07_2026-10-07.md ({len(out):,} chars)")
